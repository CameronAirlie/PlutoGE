#pragma once

#include <filesystem>
#include <string>

namespace PlutoGE::ui
{
    // Inputs for a game's C# script project. Paths are relative to the .csproj where possible.
    struct ScriptProjectLayout
    {
        std::string rootNamespace;      // "ThirdPersonProject"
        std::string sourcePattern;      // "Assets/**/*.cs"
        std::string managedOutputPath;  // "Assets/Managed"
        // This machine's PlutoGE.ScriptCore: a built assembly (installed editors) or the source project.
        std::string scriptCoreReference;
        std::string scriptCoreRuntimeDirectory;
        bool scriptCoreIsProject = false;
    };

    // The script project, free of machine-specific paths so it can be committed. It imports
    // <Name>.engine.props (this machine's engine location, regenerated by the editor and ignored by Git) and an
    // optional <Name>.custom.props / .custom.targets that the user owns for package references and analyzers.
    [[nodiscard]] std::string BuildScriptProjectText(const ScriptProjectLayout &layout);
    [[nodiscard]] std::string BuildScriptEnginePropsText(const ScriptProjectLayout &layout);
    // "<project>.engine.props" beside "<project>.csproj".
    [[nodiscard]] std::filesystem::path GetScriptEnginePropsPath(const std::filesystem::path &scriptProjectPath);

    // Version control defaults for a new project: generated and per-user files ignored, binary sources routed
    // to Git LFS when it is installed, small metadata kept in Git. Existing files are never overwritten.
    // Also adds a VS Code debugger attach configuration. Returns false with a reason if a file could not be written.
    bool WriteNewProjectFiles(const std::filesystem::path &projectRoot, std::string *errorMessage = nullptr);
    [[nodiscard]] std::string BuildGitIgnoreText();
    [[nodiscard]] std::string BuildGitAttributesText();
}
